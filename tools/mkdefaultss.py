#!/usr/bin/env python3
"""
mkdefaultss.py - build DefaultSS444.c and DefaultSS555.c, the image the
pico_shared menu screensaver bounces around when no artwork is on the SD card,
from a frame of the game.

    hosttest/build.sh
    ./hosttest/c1943_host ~/roms/arcade 1943 301 300 /tmp/ss
    tools/mkdefaultss.py /tmp/ss/frame_00300.ppm

The ROM set is not part of this project, so neither are pictures of the game:
the frame is taken from your own set by the host harness. It is a 320x240 PPM
with Tate mode Off (the game area is x 48-271); the game area is scaled to 160
rows.

The files hold the image as an unsigned char array: uint16 width, uint16 height
(little-endian), then width*height little-endian pixels, 0000RRRRGGGGBBBB
(.444) or 0RRRRRGGGGGBBBBB (.555), as pico_shared/DefaultSS.h expects.
"""

import os
import sys

HEIGHT = 160


def read_ppm(path):
    with open(path, "rb") as f:
        data = f.read()
    parts = data.split(maxsplit=4)
    assert parts[0] == b"P6", "not a binary PPM"
    w, h, maxval = int(parts[1]), int(parts[2]), int(parts[3])
    assert maxval == 255
    pix = parts[4][: w * h * 3]
    return w, h, pix


def scale(pix, w, x0, x1, y0, y1, ow, oh):
    """Area-average the rectangle [x0,x1) x [y0,y1) of an RGB24 image to ow x oh."""
    out = []
    sw, sh = x1 - x0, y1 - y0
    for oy in range(oh):
        ya, yb = y0 + oy * sh / oh, y0 + (oy + 1) * sh / oh
        for ox in range(ow):
            xa, xb = x0 + ox * sw / ow, x0 + (ox + 1) * sw / ow
            acc = [0.0, 0.0, 0.0]
            area = 0.0
            y = int(ya)
            while y < yb:
                wy = min(y + 1, yb) - max(y, ya)
                x = int(xa)
                while x < xb:
                    wx = min(x + 1, xb) - max(x, xa)
                    i = (y * w + x) * 3
                    for c in range(3):
                        acc[c] += pix[i + c] * wx * wy
                    area += wx * wy
                    x += 1
                y += 1
            out.append(tuple(int(round(a / area)) for a in acc))
    return out


def write_c(path, name, ow, oh, pixels, pack):
    data = bytearray([ow & 0xFF, ow >> 8, oh & 0xFF, oh >> 8])
    for r, g, b in pixels:
        v = pack(r, g, b)
        data += bytes([v & 0xFF, v >> 8])
    with open(path, "w") as f:
        f.write("/* Generated by tools/mkdefaultss.py - do not edit. */\n")
        f.write(f"const unsigned char {name}[] = {{\n")
        for i in range(0, len(data), 12):
            f.write("  " + ", ".join(f"0x{b:02x}" for b in data[i : i + 12]) + ",\n")
        f.write("};\n")
        f.write(f"const unsigned int {name}_len = {len(data)};\n")


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        return 1
    w, h, pix = read_ppm(sys.argv[1])
    assert (w, h) == (320, 240), "expected the 320x240 canvas (Tate off, not --tall)"
    x0, x1 = 48, 48 + 224
    ow = round(224 * HEIGHT / 240)
    pixels = scale(pix, w, x0, x1, 0, 240, ow, HEIGHT)
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
    write_c(os.path.join(root, "DefaultSS444.c"), "DefaultSS160_444", ow, HEIGHT, pixels,
            lambda r, g, b: ((r >> 4) << 8) | ((g >> 4) << 4) | (b >> 4))
    write_c(os.path.join(root, "DefaultSS555.c"), "DefaultSS160_555", ow, HEIGHT, pixels,
            lambda r, g, b: ((r >> 3) << 10) | ((g >> 3) << 5) | (b >> 3))
    print(f"DefaultSS444.c, DefaultSS555.c: {ow}x{HEIGHT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
